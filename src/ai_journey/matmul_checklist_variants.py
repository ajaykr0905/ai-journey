"""The registry of checklist kernels, their launches and each pipeline's verdict.

The checklist times kernels from three labs side by side:

- Day 74: ``matmul_x_columns`` and ``matmul_x_rows``, compiled from the Day 74
  ``SHADER_SOURCE`` unchanged. Their digest is that source's digest, and they
  run in the naive group of the config.
- Day 76: ``matmul_tiled_32``, the Day 76 kernel text unchanged.
- Day 77: one ``BlockDesign`` per checklist change, generated by
  ``matmul_checklist_source``.

Each digest covers one kernel's text alone, so adding a kernel moves no
other digest. The checklist library is the Day 76 header followed by the
Day 76 kernel and then the Day 77 kernels, in registry order.

A thread of a variant computes ``TM x TN`` outputs, so a launch covers
``ceil(N / TN) x ceil(M / TM)`` threads with x over the columns of C, in
whole groups, as Day 73 sizes every launch. ``matmul_x_rows`` keeps its own
x-over-rows grid. The guard tail of an output buffer is every output slot of
the launched groups past ``M * N``; a store that escaped its guard could
reach only that tail or another element of C.

A pipeline refuses a variant with threadgroup memory when it allows fewer
threads than the group, or when its static threadgroup memory differs from
the bytes that the kernel declares. A refusal is data, and a refused variant
never launches. The two Day 74 kernels hold no threadgroup memory, and a
checklist run needs both, so they are not admitted this way.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass

from .kernel_metal_geometry import (
    MAX_THREADGROUP_THREADS,
    LaunchGeometry,
    PipelineLimits,
    ceil_div,
    require_integer,
)
from .matmul_metal_mapping import X_COLUMNS, X_ROWS, grid_extent, require_mapping
from .matmul_metal_source import (
    MATMUL_X_COLUMNS,
    MATMUL_X_ROWS,
    SCALAR_BUFFERS,
    SHADER_SOURCE,
)
from .matmul_checklist_source import (
    MAX_THREADGROUP_BYTES,
    BlockDesign,
    MatmulChecklistError,
    block_kernel_source,
)
from .matmul_tiled_source import HEADER, threadgroup_bytes
from .matmul_tiled_variants import (
    FEWER_THREADS,
    K_ORDER_FMA,
    OTHER_THREADGROUP_BYTES,
    text_sha256,
)
from .matmul_tiled_variants import VARIANTS as TILED_VARIANTS
from .memory_access_tiling import MatmulShape

DAY_74 = "day_74_naive"
DAY_76 = "day_76_tiled"
DAY_77 = "day_77_checklist"
ORIGINS = (DAY_74, DAY_76, DAY_77)
TILED_32 = "matmul_tiled_32"
S2_COARSE = "matmul_s2_coarse_4x1"
S3_BLOCK = "matmul_s3_block_4x4"
S4_VECTOR = "matmul_s4_vec4"
S5_PAD = "matmul_s5_pad4"
S6_SMALL = "matmul_s6_group_8x8"
S6_LARGE = "matmul_s6_group_32x32"
S7_INTERIOR = "matmul_s7_interior"
DESIGNS = (
    BlockDesign(S2_COARSE, 32, 32, 32, 4, 1, False, 0, False),
    BlockDesign(S3_BLOCK, 64, 64, 16, 4, 4, False, 0, False),
    BlockDesign(S4_VECTOR, 64, 64, 16, 4, 4, True, 0, False),
    BlockDesign(S5_PAD, 64, 64, 16, 4, 4, True, 4, False),
    BlockDesign(S6_SMALL, 32, 32, 16, 4, 4, True, 4, False),
    BlockDesign(S6_LARGE, 128, 128, 16, 4, 4, True, 4, False),
    BlockDesign(S7_INTERIOR, 64, 64, 16, 4, 4, True, 4, True),
)


@dataclass(frozen=True)
class ChecklistVariant:
    """One timed kernel: where it comes from, its text, launch shape and memory."""

    name: str
    origin: str
    mapping: str
    outputs_per_thread: tuple[int, int]
    group_size: tuple[int, int] | None
    threadgroup_bytes: int
    source: str
    design: BlockDesign | None = None

    def __post_init__(self) -> None:
        if self.origin not in ORIGINS:
            raise MatmulChecklistError(f"origin must be one of {', '.join(ORIGINS)}")
        require_mapping(self.mapping)
        for pair, label in (
            (self.outputs_per_thread, "outputs_per_thread"),
            (self.group_size or (1, 1), "group_size"),
        ):
            if type(pair) is not tuple or len(pair) != 2:
                raise TypeError(f"{label} must be an (x, y) pair")
            for value in pair:
                require_integer(value, label, 1, MAX_THREADGROUP_THREADS)
        require_integer(
            self.threadgroup_bytes, "threadgroup_bytes", 0, MAX_THREADGROUP_BYTES
        )
        if (self.group_size is None) != (self.origin == DAY_74):
            raise MatmulChecklistError("only a Day 74 kernel runs in the naive group")
        if (self.design is None) != (self.origin != DAY_77):
            raise MatmulChecklistError("exactly the Day 77 kernels have a design")
        if (
            not isinstance(self.source, str)
            or not self.source.isascii()
            or f"kernel void {self.name}(" not in self.source
        ):
            raise MatmulChecklistError(
                f"{self.name} needs ASCII source that defines it"
            )

    @property
    def source_sha256(self) -> str:
        """The digest of the kernel text; for Day 74, of the whole Day 74 source."""

        return text_sha256(self.source)

    @property
    def correctness_mode(self) -> str:
        """Every checklist kernel runs the ``fma_replay`` chain in k order."""

        return K_ORDER_FMA

    @property
    def arg_casts(self) -> dict[int, str]:
        """Pass each scalar as 32 bits, the width of ``constant uint&``."""

        return {index: "int32" for index in SCALAR_BUFFERS}

    def group(self, naive_group: tuple[int, int]) -> tuple[int, int]:
        """The ``(x, y)`` group of a launch; the Day 74 kernels take the config's."""

        return naive_group if self.group_size is None else self.group_size

    def to_mapping(self) -> dict[str, object]:
        """Return what a report records about the variant, without its text."""

        return {
            "name": self.name,
            "origin": self.origin,
            "mapping": self.mapping,
            "outputs_per_thread": list(self.outputs_per_thread),
            "group_size": None if self.group_size is None else list(self.group_size),
            "threadgroup_bytes": self.threadgroup_bytes,
            "correctness_mode": self.correctness_mode,
            "design": None if self.design is None else self.design.to_mapping(),
            "source_sha256": self.source_sha256,
        }


def _naive(name: str, mapping: str) -> ChecklistVariant:
    return ChecklistVariant(name, DAY_74, mapping, (1, 1), None, 0, SHADER_SOURCE)


def _block(design: BlockDesign) -> ChecklistVariant:
    return ChecklistVariant(
        name=design.name,
        origin=DAY_77,
        mapping=X_COLUMNS,
        outputs_per_thread=(design.thread_m, design.thread_n),
        group_size=design.group_size,
        threadgroup_bytes=design.threadgroup_bytes,
        source=block_kernel_source(design),
        design=design,
    )


_TILED = TILED_VARIANTS[TILED_32]
VARIANTS: dict[str, ChecklistVariant] = {
    variant.name: variant
    for variant in (
        _naive(MATMUL_X_COLUMNS, X_COLUMNS),
        _naive(MATMUL_X_ROWS, X_ROWS),
        ChecklistVariant(
            TILED_32,
            DAY_76,
            X_COLUMNS,
            (1, 1),
            _TILED.group_size,
            threadgroup_bytes(_TILED.tile),
            _TILED.source,
        ),
        *map(_block, DESIGNS),
    )
}
NAIVE_VARIANTS = tuple(
    name for name, variant in VARIANTS.items() if variant.origin == DAY_74
)
LIBRARY_VARIANTS = tuple(
    name for name, variant in VARIANTS.items() if variant.origin != DAY_74
)


def checklist_library() -> str:
    """Join the header, the Day 76 kernel and the Day 77 kernels into one text."""

    return HEADER + "".join("\n" + VARIANTS[name].source for name in LIBRARY_VARIANTS)


def variant_launch(
    variant: ChecklistVariant, shape: MatmulShape, naive_group: tuple[int, int]
) -> LaunchGeometry:
    """Size one launch: ``TM x TN`` outputs per thread over whole groups."""

    if not isinstance(variant, ChecklistVariant):
        raise TypeError("variant must be a ChecklistVariant")
    if variant.mapping == X_ROWS:
        extent = grid_extent(X_ROWS, shape)
    else:
        rows, columns = variant.outputs_per_thread
        extent = (ceil_div(shape.n, columns), ceil_div(shape.m, rows))
    return LaunchGeometry(extent=extent, group_size=variant.group(naive_group))


def guard_elements(
    variant: ChecklistVariant, shape: MatmulShape, launch: LaunchGeometry
) -> int:
    """Output slots of the launched groups past ``M * N``: the sentinel tail."""

    rows, columns = variant.outputs_per_thread
    x, y = launch.threads
    return x * y * rows * columns - shape.m * shape.n


@dataclass(frozen=True)
class ChecklistAdmission:
    """One pipeline's verdict on one variant with threadgroup memory."""

    variant: ChecklistVariant
    limits: PipelineLimits

    def __post_init__(self) -> None:
        if not isinstance(self.variant, ChecklistVariant):
            raise TypeError("variant must be a ChecklistVariant")
        if self.variant.group_size is None:
            raise MatmulChecklistError("the Day 74 kernels are not admitted by tile")
        if not isinstance(self.limits, PipelineLimits):
            raise TypeError("limits must be PipelineLimits")

    @property
    def required_threads(self) -> int:
        """Threads in one group of the variant."""

        x, y = self.variant.group_size
        return x * y

    @property
    def reason(self) -> str | None:
        """The first rule the pipeline breaks, or ``None`` when it admits the variant."""

        if self.limits.max_threads_per_threadgroup < self.required_threads:
            return FEWER_THREADS
        if (
            self.limits.static_threadgroup_memory_bytes
            != self.variant.threadgroup_bytes
        ):
            return OTHER_THREADGROUP_BYTES
        return None

    @property
    def admitted(self) -> bool:
        """Whether the variant may launch on this pipeline."""

        return self.reason is None

    def to_mapping(self) -> dict[str, object]:
        """Return the verdict as a report records it."""

        return {
            "name": self.variant.name,
            "admitted": self.admitted,
            "reason": self.reason,
            "required_threads": self.required_threads,
            "allowed_threads": self.limits.max_threads_per_threadgroup,
            "declared_threadgroup_bytes": self.variant.threadgroup_bytes,
            "static_threadgroup_bytes": self.limits.static_threadgroup_memory_bytes,
        }


def admitted_names(admissions: dict[str, ChecklistAdmission]) -> tuple[str, ...]:
    """Return every variant that may launch, in registry order."""

    return tuple(
        name for name in VARIANTS if name in NAIVE_VARIANTS or admissions[name].admitted
    )


def require_known(names: Iterable[object]) -> tuple[str, ...]:
    """Return registered names in their order, each at most once."""

    chosen = tuple(names)
    for name in chosen:
        if name not in VARIANTS:
            raise MatmulChecklistError(f"{name!r} is not a registered variant")
    if len(set(chosen)) != len(chosen):
        raise MatmulChecklistError("a variant may appear only once")
    return chosen
