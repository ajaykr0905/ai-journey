"""Prometheus recording and alerting rules generated from declared SLOs.

``build_rule_file`` turns the config's objectives into two rule groups. The
``ai_journey_serving_recovery_slo`` group first records the attempt-success,
request-success and post-fault latency ratios, then alerts on every serving
objective; ``ai_journey_worker_recovery_slo`` alerts on the worker
objectives. Each alert names the objective it guards in an ``slo`` label and
every rule adds ``scope="local_cpu_lab"``. A duration objective compares a
seconds gauge with the objective converted once from integer milliseconds,
and the latency objective reads the cumulative bucket at the declared bound,
which the config guarantees is a bucket. ``for`` is omitted: the exposition
is one snapshot of a finished run, so there is no later scrape to wait for.

``render_rule_file`` writes the constrained YAML subset. ``parse_rule_file``
reads it back strictly and checks the structure Prometheus' rule loader
checks, and more: unique group and rule names, exactly one of ``record`` or
``alert``, ``level:metric:operations`` recording names, CamelCase alert
names, valid unreserved label names, literal printable annotations without
templates, every expression in the canonical PromQL subset, and the exact
canonical bytes. ``validate_rule_file`` binds each selector to a metric set,
and ``evaluate_rule_file`` evaluates the groups in order at one instant.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass

from .telemetry_metrics_config import TelemetryMetricsConfig
from .telemetry_metrics_exposition import Sample, flatten_samples, format_value
from .telemetry_metrics_model import (
    LAB_SCOPE,
    SCOPE_LABEL,
    MetricFamily,
    MetricSet,
    TelemetryMetricsError,
    require_label_name,
)
from .telemetry_metrics_promql import (
    Comparison,
    Expression,
    Matcher,
    Ratio,
    Selector,
    SumBy,
    evaluate,
    parse_expression,
    render,
    selectors,
)
from .telemetry_metrics_yaml import emit_yaml, read_yaml

SERVING = "ai_journey_serving_recovery_"
WORKER = "ai_journey_worker_recovery_"
SERVING_GROUP = "ai_journey_serving_recovery_slo"
WORKER_GROUP = "ai_journey_worker_recovery_slo"
POST_FAULT_LATENCY_RATIO = "scope:ai_journey_serving_recovery_success_latency:post_fault_within_objective_ratio"
HEADER = (
    "Generated by ai_journey.telemetry_metrics_rules from declared lab objectives.",
    "Local CPU lab telemetry rules; they guard no production service.",
)
_RECORD = re.compile(r"[a-zA-Z_][a-zA-Z0-9_]*:[a-zA-Z_][a-zA-Z0-9_]*:[a-zA-Z0-9_]+")
_ALERT = re.compile(r"[A-Z][A-Za-z0-9]{0,127}")
_GROUP = re.compile(r"[a-zA-Z_][a-zA-Z0-9_]{0,127}")
_RECORDING_FIELDS = ("record", "expr", "labels")
_ALERTING_FIELDS = ("alert", "expr", "labels", "annotations")


def _text_pairs(pairs: object, what: str) -> tuple[tuple[str, str], ...]:
    if type(pairs) is not tuple or not pairs:
        raise TelemetryMetricsError(f"{what} must be a non-empty tuple of pairs")
    for pair in pairs:
        if type(pair) is not tuple or len(pair) != 2:
            raise TelemetryMetricsError(f"{what} must be (name, text) pairs")
        name, text = pair
        require_label_name(name)
        if name == "alertname":
            raise TelemetryMetricsError(f"{what} must not set alertname")
        if type(text) is not str or not text or not text.isprintable():
            raise TelemetryMetricsError(f"{what} values must be printable text")
        if "{{" in text:
            raise TelemetryMetricsError(f"{what} are literal text without templates")
    names = [name for name, _ in pairs]
    if names != sorted(set(names)):
        raise TelemetryMetricsError(f"{what} must be sorted by unique name")
    return pairs


@dataclass(frozen=True)
class RecordingRule:
    """A precomputed series named level:metric:operations."""

    record: str
    expr: Expression
    labels: tuple[tuple[str, str], ...]

    def __post_init__(self) -> None:
        if type(self.record) is not str or _RECORD.fullmatch(self.record) is None:
            raise TelemetryMetricsError(
                f"recording rule {self.record!r} is not level:metric:operations"
            )
        if type(self.expr) not in (SumBy, Ratio):
            raise TelemetryMetricsError("recording rules record a sum or a ratio")
        _text_pairs(self.labels, "rule labels")

    @property
    def name(self) -> str:
        return self.record


@dataclass(frozen=True)
class AlertingRule:
    """An alert that fires for every series its threshold comparison keeps."""

    alert: str
    expr: Comparison
    labels: tuple[tuple[str, str], ...]
    annotations: tuple[tuple[str, str], ...]

    def __post_init__(self) -> None:
        if type(self.alert) is not str or _ALERT.fullmatch(self.alert) is None:
            raise TelemetryMetricsError(f"alert {self.alert!r} must be CamelCase")
        if type(self.expr) is not Comparison:
            raise TelemetryMetricsError("alerting rules compare with a threshold")
        _text_pairs(self.labels, "rule labels")
        _text_pairs(self.annotations, "annotations")

    @property
    def name(self) -> str:
        return self.alert


@dataclass(frozen=True)
class RuleGroup:
    """Rules that Prometheus evaluates in order at one instant."""

    name: str
    rules: tuple[RecordingRule | AlertingRule, ...]

    def __post_init__(self) -> None:
        if type(self.name) is not str or _GROUP.fullmatch(self.name) is None:
            raise TelemetryMetricsError(f"invalid rule group name: {self.name!r}")
        if (
            type(self.rules) is not tuple
            or not self.rules
            or any(
                type(rule) not in (RecordingRule, AlertingRule) for rule in self.rules
            )
        ):
            raise TelemetryMetricsError(f"group {self.name} needs rules")


@dataclass(frozen=True)
class RuleFile:
    """Rule groups with unique group names and unique rule names."""

    groups: tuple[RuleGroup, ...]

    def __post_init__(self) -> None:
        if (
            type(self.groups) is not tuple
            or not self.groups
            or any(type(group) is not RuleGroup for group in self.groups)
        ):
            raise TelemetryMetricsError("a rule file needs RuleGroup values")
        names = [group.name for group in self.groups]
        if len(set(names)) != len(names):
            raise TelemetryMetricsError("rule group names repeat")
        rules = [rule.name for rule in self.rules]
        if len(set(rules)) != len(rules):
            raise TelemetryMetricsError("rule names repeat")

    @property
    def rules(self) -> tuple[RecordingRule | AlertingRule, ...]:
        return tuple(rule for group in self.groups for rule in group.rules)


@dataclass(frozen=True)
class DeclaredObjective:
    """One declared objective and the alert that guards it."""

    slo: str
    alert: str
    expr: Comparison
    summary: str


def _selector(metric: str, **labels: str) -> Selector:
    return Selector(
        metric,
        tuple(Matcher(name, "=", value) for name, value in sorted(labels.items())),
    )


def _ratio(numerator: Selector, denominator: Selector) -> Ratio:
    return Ratio(SumBy((SCOPE_LABEL,), numerator), SumBy((SCOPE_LABEL,), denominator))


def _seconds(milliseconds: int) -> float:
    return milliseconds / 1000


def recording_rules(config: TelemetryMetricsConfig) -> tuple[RecordingRule, ...]:
    """The serving ratios that dashboards and the latency alert read."""

    bound = format_value(config.serving.post_fault_latency_us / 10**6)
    latency = SERVING + "success_latency_seconds"
    succeeded = Selector(
        SERVING + "requests_total",
        (Matcher("outcome", "!=", "failed_after_budget"),),
    )
    labels = ((SCOPE_LABEL, LAB_SCOPE),)
    return (
        RecordingRule(
            "scope:ai_journey_serving_recovery_attempts:ok_ratio",
            _ratio(
                _selector(SERVING + "attempts_total", outcome="ok"),
                _selector(SERVING + "attempts_total"),
            ),
            labels,
        ),
        RecordingRule(
            "scope:ai_journey_serving_recovery_requests:success_ratio",
            _ratio(succeeded, _selector(SERVING + "requests_total")),
            labels,
        ),
        RecordingRule(
            POST_FAULT_LATENCY_RATIO,
            _ratio(
                _selector(latency + "_bucket", le=bound, phase="post_fault"),
                _selector(latency + "_count", phase="post_fault"),
            ),
            labels,
        ),
    )


def declared_objectives(
    config: TelemetryMetricsConfig,
) -> tuple[tuple[str, tuple[DeclaredObjective, ...]], ...]:
    """Every declared objective by rule group, each with its guarding alert."""

    if not isinstance(config, TelemetryMetricsConfig):
        raise TypeError("config must be TelemetryMetricsConfig")
    serving, worker = config.serving, config.worker

    def slower(metric: str, milliseconds: int) -> Comparison:
        return Comparison(_selector(metric), ">", _seconds(milliseconds))

    def seconds(milliseconds: int) -> str:
        return format_value(_seconds(milliseconds)) + " s"

    ratio = serving.post_fault_within_latency_ratio
    latency = format_value(serving.post_fault_latency_us / 1000) + " ms"
    return (
        (
            SERVING_GROUP,
            (
                DeclaredObjective(
                    "serving-detection-latency",
                    "ServingRecoveryDetectionSlow",
                    slower(
                        SERVING + "detection_latency_seconds",
                        serving.detection_latency_ms,
                    ),
                    "Kill-to-observed-exit detection took longer than "
                    + seconds(serving.detection_latency_ms),
                ),
                DeclaredObjective(
                    "serving-restart-latency",
                    "ServingRecoveryRestartSlow",
                    slower(
                        SERVING + "restart_latency_seconds", serving.restart_latency_ms
                    ),
                    "Exit-to-ready restart took longer than "
                    + seconds(serving.restart_latency_ms),
                ),
                DeclaredObjective(
                    "serving-unavailability",
                    "ServingRecoveryUnavailabilityLong",
                    slower(
                        SERVING + "unavailability_seconds", serving.unavailability_ms
                    ),
                    "Client-observed unavailability lasted longer than "
                    + seconds(serving.unavailability_ms),
                ),
                DeclaredObjective(
                    "serving-time-to-slo-recovery",
                    "ServingRecoverySloRecoverySlow",
                    slower(
                        SERVING + "time_to_slo_recovery_seconds",
                        serving.time_to_slo_recovery_ms,
                    ),
                    "Kill-to-SLO-recovery took longer than "
                    + seconds(serving.time_to_slo_recovery_ms),
                ),
                DeclaredObjective(
                    "serving-recovered",
                    "ServingRecoveryNotRecovered",
                    Comparison(_selector(SERVING + "recovered"), "<", 1.0),
                    "The run did not recover: a request failed or SLO recovery "
                    "was never observed",
                ),
                DeclaredObjective(
                    "serving-request-success",
                    "ServingRecoveryRequestsFailed",
                    Comparison(
                        _selector(
                            SERVING + "requests_total", outcome="failed_after_budget"
                        ),
                        ">",
                        0.0,
                    ),
                    "A logical request failed after its whole retry budget",
                ),
                DeclaredObjective(
                    "serving-post-fault-latency",
                    "ServingRecoveryPostFaultLatencyMissed",
                    Comparison(_selector(POST_FAULT_LATENCY_RATIO), "<", ratio),
                    f"Fewer than {format_value(ratio)} of post-fault successes took "
                    f"at most {latency}",
                ),
            ),
        ),
        (
            WORKER_GROUP,
            (
                DeclaredObjective(
                    "worker-detection",
                    "WorkerRecoveryDetectionSlow",
                    slower(WORKER + "detection_seconds", worker.detection_ms),
                    "Kill-to-detection took longer than "
                    + seconds(worker.detection_ms),
                ),
                DeclaredObjective(
                    "worker-recovery-time",
                    "WorkerRecoverySlow",
                    slower(WORKER + "recovery_seconds", worker.recovery_ms),
                    "Kill-to-completed recovery took longer than "
                    + seconds(worker.recovery_ms),
                ),
                DeclaredObjective(
                    "worker-no-omitted-items",
                    "WorkerRecoveryItemsOmitted",
                    Comparison(_selector(WORKER + "omitted_items_total"), ">", 0.0),
                    "The final result omitted workload items",
                ),
                DeclaredObjective(
                    "worker-no-duplicated-items",
                    "WorkerRecoveryItemsDuplicated",
                    Comparison(_selector(WORKER + "duplicated_items_total"), ">", 0.0),
                    "The final result committed an item more than once",
                ),
            ),
        ),
    )


def _alert(objective: DeclaredObjective) -> AlertingRule:
    return AlertingRule(
        objective.alert,
        objective.expr,
        ((SCOPE_LABEL, LAB_SCOPE), ("slo", objective.slo)),
        (
            (
                "description",
                "Local CPU lab telemetry derived from sealed recovery evidence; the "
                "threshold is a declared lab objective, not a production SLO.",
            ),
            ("summary", objective.summary),
        ),
    )


def build_rule_file(config: TelemetryMetricsConfig) -> RuleFile:
    """Generate the recording and alerting rules for the declared objectives."""

    groups = []
    for name, objectives in declared_objectives(config):
        recorded = recording_rules(config) if name == SERVING_GROUP else ()
        groups.append(
            RuleGroup(name, (*recorded, *(_alert(item) for item in objectives)))
        )
    return RuleFile(tuple(groups))


def _rule_mapping(rule: RecordingRule | AlertingRule) -> dict[str, object]:
    mapping: dict[str, object] = (
        {"record": rule.record}
        if type(rule) is RecordingRule
        else {"alert": rule.alert}
    )
    mapping["expr"] = render(rule.expr)
    mapping["labels"] = dict(rule.labels)
    if type(rule) is AlertingRule:
        mapping["annotations"] = dict(rule.annotations)
    return mapping


def render_rule_file(rule_file: RuleFile) -> str:
    """Write a rule file as the constrained YAML subset with a fixed header."""

    if type(rule_file) is not RuleFile:
        raise TypeError("rule_file must be RuleFile")
    document = {
        "groups": [
            {"name": group.name, "rules": [_rule_mapping(rule) for rule in group.rules]}
            for group in rule_file.groups
        ]
    }
    return emit_yaml(document, comments=HEADER)


def _fields(value: object, names: Sequence[str], what: str) -> dict:
    if type(value) is not dict or list(value) != list(names):
        raise TelemetryMetricsError(f"{what} fields must be {', '.join(names)}")
    return value


def _pairs(value: object, what: str) -> tuple[tuple[str, str], ...]:
    if type(value) is not dict:
        raise TelemetryMetricsError(f"{what} must be a mapping")
    return tuple(value.items())


def _expression(value: object) -> Expression:
    if type(value) is not str:
        raise TelemetryMetricsError("expr must be one PromQL string")
    return parse_expression(value)


def _rule(mapping: object) -> RecordingRule | AlertingRule:
    if type(mapping) is dict and "record" in mapping:
        rule = _fields(mapping, _RECORDING_FIELDS, "recording rule")
        return RecordingRule(
            rule["record"],
            _expression(rule["expr"]),
            _pairs(rule["labels"], "rule labels"),
        )
    rule = _fields(mapping, _ALERTING_FIELDS, "alerting rule")
    return AlertingRule(
        rule["alert"],
        _expression(rule["expr"]),
        _pairs(rule["labels"], "rule labels"),
        _pairs(rule["annotations"], "annotations"),
    )


def parse_rule_file(text: str) -> RuleFile:
    """Read a rule file strictly; only the exact canonical bytes are accepted."""

    document = _fields(read_yaml(text), ("groups",), "rule file")
    if type(document["groups"]) is not list:
        raise TelemetryMetricsError("groups must be a sequence")
    groups = []
    for mapping in document["groups"]:
        group = _fields(mapping, ("name", "rules"), "rule group")
        if type(group["rules"]) is not list:
            raise TelemetryMetricsError("rules must be a sequence")
        groups.append(
            RuleGroup(group["name"], tuple(_rule(rule) for rule in group["rules"]))
        )
    rule_file = RuleFile(tuple(groups))
    if render_rule_file(rule_file) != text:
        raise TelemetryMetricsError("rule file is not in canonical form")
    return rule_file


def _output_labels(rule: RecordingRule) -> frozenset[str]:
    """A sum or ratio keeps its grouping labels; rule labels are added."""

    expr = rule.expr
    grouping = expr.numerator.labels if type(expr) is Ratio else expr.labels
    return frozenset(grouping) | {name for name, _ in rule.labels}


def validate_rule_file(rule_file: RuleFile, metrics: MetricSet) -> None:
    """Bind every selector to the metric set the rules will be evaluated on.

    A selector must read a sample name of the set or a recording rule defined
    earlier in the same group, since only those exist when the rule runs.
    Matchers must name labels the series carry and values that occur in the
    family, and an ``le`` matcher must spell one of the family's bounds.
    """

    if type(rule_file) is not RuleFile or type(metrics) is not MetricSet:
        raise TypeError("validate_rule_file needs a RuleFile and a MetricSet")
    families = {
        sample: family for family in metrics.families for sample in family.sample_names
    }
    for group in rule_file.groups:
        recorded: dict[str, frozenset[str]] = {}
        for rule in group.rules:
            for selector in selectors(rule.expr):
                _check_selector(rule.name, selector, families, recorded)
            if type(rule) is RecordingRule:
                if rule.record in families:
                    raise TelemetryMetricsError(
                        f"recording rule {rule.record} shadows an exported sample"
                    )
                recorded[rule.record] = _output_labels(rule)


def _check_selector(
    rule: str,
    selector: Selector,
    families: dict[str, MetricFamily],
    recorded: dict[str, frozenset[str]],
) -> None:
    if selector.metric in recorded:
        unknown = {m.label for m in selector.matchers} - recorded[selector.metric]
        if unknown:
            raise TelemetryMetricsError(
                f"{rule} matches labels {sorted(unknown)} that "
                f"{selector.metric} does not record"
            )
        return
    family = families.get(selector.metric)
    if family is None:
        raise TelemetryMetricsError(
            f"{rule} reads {selector.metric}, which is neither exported nor "
            "recorded earlier in its group"
        )
    for matcher in selector.matchers:
        if matcher.label == "le" and selector.metric == family.name + "_bucket":
            allowed = {format_value(bound) for bound in family.buckets} | {"+Inf"}
        elif matcher.label in family.label_names:
            allowed = {series.label_map()[matcher.label] for series in family.series}
        else:
            raise TelemetryMetricsError(
                f"{rule} matches label {matcher.label}, which {selector.metric} "
                "does not carry"
            )
        if matcher.value not in allowed:
            raise TelemetryMetricsError(
                f"{rule} matches {matcher.label}={matcher.value!r}, which no "
                f"{family.name} series carries"
            )


@dataclass(frozen=True)
class FiringAlert:
    """An alert that fires at the evaluation instant, with its labels and value."""

    alert: str
    labels: tuple[tuple[str, str], ...]
    value: str


def evaluate_rule_file(
    rule_file: RuleFile, metrics: MetricSet
) -> tuple[FiringAlert, ...]:
    """Evaluate groups in order at one instant; return the alerts that fire.

    Recording-rule outputs join the group's samples as Prometheus writes them
    before the next rule runs, with rule labels overriding result labels. An
    alert's labels add ``alertname``, and its value keeps the exposition
    spelling, so ``+Inf`` or ``NaN`` stay representable in JSON.
    """

    validate_rule_file(rule_file, metrics)
    exported = flatten_samples(metrics)
    firing = []
    for group in rule_file.groups:
        recorded: list[Sample] = []
        for rule in group.rules:
            for element in evaluate(rule.expr, (*exported, *recorded)):
                labels = tuple(
                    sorted((dict(element.labels) | dict(rule.labels)).items())
                )
                if type(rule) is RecordingRule:
                    recorded.append(Sample(rule.record, labels, element.value))
                else:
                    firing.append(
                        FiringAlert(
                            rule.alert,
                            tuple(sorted(labels + (("alertname", rule.alert),))),
                            format_value(element.value),
                        )
                    )
    return tuple(sorted(firing, key=lambda alert: (alert.alert, alert.labels)))
