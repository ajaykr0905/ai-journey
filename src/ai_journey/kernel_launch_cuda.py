"""Pinned CUDA C++ source for the lab kernels, and a compiler-free check of it.

``cuda_source`` writes both kernels and their host launchers from the launch
math that the simulator uses: one thread per element, grids sized by
``cdiv`` on each axis, the same guards, and the same integer grayscale rule.
This lab never compiles or runs the text. It is source for a later run on
an NVIDIA GPU. ``check_cuda_source`` reads the text back without a compiler.
It confirms the ``__global__`` signatures, the index expressions, the guards
and the grayscale arithmetic. It then evaluates the host grid sizing for the
given extents and requires the simulator's launch configurations. Each
function must hold exactly its pinned statements, and the text must hold no
other code, because one extra statement or overload can change the launch.
Comments are read left to right, as a compiler reads them, and text that a
line splice or a trigraph can change fails every check.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .kernel_launch_config import (
    Dim3,
    KernelLaunchError,
    LaunchConfig,
    launch_1d,
    launch_2d,
)
from .kernel_launch_kernels import GRAYSCALE_WEIGHTS_PER_10000

CUDA_LANGUAGE = "CUDA C++"
CHECK_NAMES = (
    "cdiv_definition",
    "vector_add_signature",
    "vector_add_index",
    "vector_add_guard",
    "vector_add_grid",
    "rgb_to_grayscale_signature",
    "rgb_to_grayscale_index",
    "rgb_to_grayscale_guard",
    "rgb_to_grayscale_rule",
    "rgb_to_grayscale_grid",
)
_UNSIGNED_WRAP = 2**32
_CDIV = "__host__ __device__ inline unsigned int cdiv(unsigned int a, unsigned int b)"
_VECTOR_KERNEL = (
    "__global__ void vector_add_kernel(const float* a, const float* b, float* out, "
    "int n)"
)
_GRAY_KERNEL = (
    "__global__ void rgb_to_grayscale_kernel(const unsigned char* rgb, "
    "unsigned char* gray, int width, int height)"
)
_VECTOR_HOST = (
    "void launch_vector_add(const float* a, const float* b, float* out, int n)"
)
_GRAY_HOST = (
    "void launch_rgb_to_grayscale(const unsigned char* rgb, unsigned char* gray, "
    "int width, int height)"
)
_DEFINITIONS = (_CDIV, _VECTOR_KERNEL, _GRAY_KERNEL, _VECTOR_HOST, _GRAY_HOST)
_VECTOR_INDEX = ("int i = blockIdx.x * blockDim.x + threadIdx.x;",)
_VECTOR_GUARDED = ("out[i] = a[i] + b[i];",)
_GRAY_INDEX = (
    "int col = blockIdx.x * blockDim.x + threadIdx.x;",
    "int row = blockIdx.y * blockDim.y + threadIdx.y;",
)
_GRAY_LOADS = (
    "int pixel = row * width + col;",
    "unsigned int r = rgb[3 * pixel];",
    "unsigned int g = rgb[3 * pixel + 1];",
    "unsigned int b = rgb[3 * pixel + 2];",
)
_GRAY_STORE = "gray[pixel] = (unsigned char)(luma < 255u ? luma : 255u);"
# C reads a literal with a leading zero as octal, so each dim3 literal starts
# with 1-9. At most 10 digits, the width of an unsigned int, keep int() bounded.
_DECIMAL = r"([1-9][0-9]{0,9})"
_COMMENT_OPENER = re.compile(r"//|/\*")
_LINE_END = re.compile(r"[\n\r]")
_VECTOR_LAUNCHER = re.compile(
    rf"dim3 block\({_DECIMAL}\);dim3 grid\(cdiv\(n,{_DECIMAL}\)\);"
    r"vector_add_kernel<<<grid,block>>>\(a,b,out,n\);"
)
_GRAY_LAUNCHER = re.compile(
    rf"dim3 block\({_DECIMAL},{_DECIMAL}\);"
    rf"dim3 grid\(cdiv\(width,{_DECIMAL}\),cdiv\(height,{_DECIMAL}\)\);"
    r"rgb_to_grayscale_kernel<<<grid,block>>>\(rgb,gray,width,height\);"
)


def _luma_statement() -> str:
    red, green, blue = GRAYSCALE_WEIGHTS_PER_10000
    return (
        f"unsigned int luma = ({red}u * r + {green}u * g + {blue}u * b + 5000u) "
        "/ 10000u;"
    )


def cuda_source(*, threads_per_block: int, block: tuple[int, int]) -> str:
    """Return the pinned CUDA C++ text for one vector block and one 2D block.

    The block sizes are checked as ``LaunchConfig`` blocks first, so the text
    never names a block that the simulator would refuse.
    """

    launch_1d(1, threads_per_block)
    if type(block) is not tuple or len(block) != 2:
        raise KernelLaunchError("block must be a (block_x, block_y) tuple")
    launch_2d(1, 1, *block)
    block_x, block_y = block
    return f"""\
// CUDA C++ source generated by ai_journey.kernel_launch_cuda.
// The lab that generated this text did not compile or run it.
// It is source for a later run on an NVIDIA GPU.
// Launch math matches the simulator: one thread per element, a grid of
// cdiv(extent, block) blocks on each axis, and a bounds guard per kernel.

{_CDIV} {{
    return (a + b - 1) / b;
}}

__global__ void vector_add_kernel(
    const float* a, const float* b, float* out, int n) {{
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n) {{
        out[i] = a[i] + b[i];
    }}
}}

// Exact rule: round the weighted sum half up, then clamp to 255.
__global__ void rgb_to_grayscale_kernel(
    const unsigned char* rgb, unsigned char* gray, int width, int height) {{
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    if (col < width && row < height) {{
        int pixel = row * width + col;
        unsigned int r = rgb[3 * pixel];
        unsigned int g = rgb[3 * pixel + 1];
        unsigned int b = rgb[3 * pixel + 2];
        {_luma_statement()}
        gray[pixel] = (unsigned char)(luma < 255u ? luma : 255u);
    }}
}}

void launch_vector_add(const float* a, const float* b, float* out, int n) {{
    dim3 block({threads_per_block});
    dim3 grid(cdiv(n, {threads_per_block}));
    vector_add_kernel<<<grid, block>>>(a, b, out, n);
}}

void launch_rgb_to_grayscale(
    const unsigned char* rgb, unsigned char* gray, int width, int height) {{
    dim3 block({block_x}, {block_y});
    dim3 grid(cdiv(width, {block_x}), cdiv(height, {block_y}));
    rgb_to_grayscale_kernel<<<grid, block>>>(rgb, gray, width, height);
}}
"""


def _code(text: str) -> str | None:
    """Replace each comment with a space, or return ``None`` for unsafe text.

    A compiler joins a line that ends in a backslash to the next line before
    it removes comments, and a compiler that reads trigraphs reads ``??/``
    as a backslash. Such a splice can move code into a comment, so text with
    a backslash or ``??`` is refused. Comments are found left to right, as a
    compiler finds them: ``/*`` inside a ``//`` comment opens nothing, and a
    ``//`` comment ends at a line feed or a carriage return. An unterminated
    ``/*`` is refused. Each search starts where the last one stopped, so the
    time is linear in the length of the text.
    """

    if "\\" in text or "??" in text:
        return None
    pieces: list[str] = []
    position = 0
    while (opener := _COMMENT_OPENER.search(text, position)) is not None:
        pieces += (text[position : opener.start()], " ")
        if opener.group() == "//":
            end = _LINE_END.search(text, opener.end())
            position = len(text) if end is None else end.start()
        else:
            close = text.find("*/", opener.end())
            if close < 0:
                return None
            position = close + 2
    pieces.append(text[position:])
    return "".join(pieces)


def _normalize(code: str) -> str:
    """Drop every space that does not separate two identifiers."""

    code = re.sub(r"\s+", " ", code).strip()
    return re.sub(r" (?=\W)|(?<=\W) ", "", code)


def _braced(text: str, opening: int) -> str | None:
    """Return the text inside the brace pair that opens at ``opening``."""

    depth = 0
    for position in range(opening, len(text)):
        if text[position] == "{":
            depth += 1
        elif text[position] == "}":
            depth -= 1
            if depth == 0:
                return text[opening + 1 : position]
    return None


def _function_body(text: str, signature: str) -> str | None:
    """Return the body of the one function with ``signature``, or ``None``."""

    head = _normalize(signature) + "{"
    start = text.find(head)
    if start < 0 or text.find(head, start + 1) >= 0:
        return None
    return _braced(text, start + len(head) - 1)


def _definitions(source: str) -> tuple[str, ...] | None:
    """Return the five function bodies if the text is those definitions only.

    Other code, such as an ``int`` overload of ``cdiv`` or a macro, can
    change what the five functions do, so it fails the whole text.
    """

    bodies = [_function_body(source, signature) for signature in _DEFINITIONS]
    if any(body is None for body in bodies):
        return None
    rebuilt = "".join(
        f"{_normalize(signature)}{{{body}}}"
        for signature, body in zip(_DEFINITIONS, bodies)
    )
    return tuple(bodies) if rebuilt == source else None


def _guarded(body: str, condition: str) -> tuple[str, str, str] | None:
    """Split a body at its one guard: code before, inside and after the block."""

    head = _normalize(f"if ({condition}) {{")
    start = body.find(head)
    if start < 0 or body.find(head, start + 1) >= 0:
        return None
    inside = _braced(body, start + len(head) - 1)
    if inside is None:
        return None
    end = start + len(head) + len(inside) + 1
    return body[:start], inside, body[end:]


def _statements(code: str) -> tuple[str, ...]:
    """Split normalized code after each semicolon; a trailing rest stays."""

    pieces = code.split(";")
    statements = tuple(f"{piece};" for piece in pieces[:-1])
    return statements + ((pieces[-1],) if pieces[-1] else ())


def _expected(*statements: str) -> tuple[str, ...]:
    return tuple(_normalize(statement) for statement in statements)


def _touches(text: str, *buffers: str) -> bool:
    return re.search(r"\b(?:" + "|".join(buffers) + r")\[", text) is not None


def _cdiv(numerator: int, denominator: int) -> int:
    # The launchers pass int extents to cdiv(unsigned int, unsigned int).
    return ((numerator + denominator - 1) % _UNSIGNED_WRAP) // denominator


def _host_launch(
    host: str, pattern: re.Pattern[str], extents: tuple[int, ...]
) -> LaunchConfig | None:
    """Evaluate a launcher that is exactly a block, a grid and one launch.

    Each grid axis must divide its extent by that axis of the block, so a
    divisor that agrees with the block only for one extent still fails.
    """

    found = pattern.fullmatch(host)
    if found is None:
        return None
    values = tuple(int(value) for value in found.groups())
    block, divisors = values[: len(extents)], values[len(extents) :]
    if divisors != block:
        return None
    try:
        return LaunchConfig(
            Dim3(*(_cdiv(size, divisor) for size, divisor in zip(extents, divisors))),
            Dim3(*block),
        )
    except (KernelLaunchError, TypeError):
        return None


@dataclass(frozen=True)
class CudaSourceCheck:
    """What a compiler-free reading of the CUDA text confirmed, check by check."""

    checks: tuple[tuple[str, bool], ...]
    vector_add_launch: LaunchConfig | None
    rgb_to_grayscale_launch: LaunchConfig | None

    @property
    def passed(self) -> bool:
        return all(result for _, result in self.checks)

    @property
    def failures(self) -> tuple[str, ...]:
        return tuple(name for name, result in self.checks if not result)

    def to_mapping(self) -> dict[str, object]:
        return {
            "checks": dict(self.checks),
            "passed": self.passed,
            "launches": {
                "vector_add": None
                if self.vector_add_launch is None
                else self.vector_add_launch.to_mapping(),
                "rgb_to_grayscale": None
                if self.rgb_to_grayscale_launch is None
                else self.rgb_to_grayscale_launch.to_mapping(),
            },
        }


def check_cuda_source(
    text: str,
    *,
    n: int,
    threads_per_block: int,
    width: int,
    height: int,
    block: tuple[int, int],
) -> CudaSourceCheck:
    """Check the CUDA text's structure and its grid sizing for given extents.

    Each kernel must be its index statements, then one guard whose block
    holds exactly the pinned statements, and nothing after it. Each grid
    check evaluates the host ``dim3`` expressions with C unsigned division
    and passes only if the result equals the configuration that the
    simulator launches for the same extent and block. Text with code beyond
    the five definitions, a line splice, a trigraph or an unterminated
    comment fails every check.
    """

    if type(text) is not str:
        raise TypeError("CUDA source must be a string")
    expected_vector = launch_1d(n, threads_per_block)
    if type(block) is not tuple or len(block) != 2:
        raise KernelLaunchError("block must be a (block_x, block_y) tuple")
    expected_gray = launch_2d(width, height, *block)
    code = _code(text)
    bodies = None if code is None else _definitions(_normalize(code))
    if bodies is None:
        return CudaSourceCheck(
            checks=tuple((name, False) for name in CHECK_NAMES),
            vector_add_launch=None,
            rgb_to_grayscale_launch=None,
        )
    cdiv, vector, gray, vector_host, gray_host = bodies
    vector_index = vector_safe = False
    vector_guard = _guarded(vector, "i < n")
    if vector_guard is not None:
        before, inside, after = vector_guard
        vector_index = _statements(before) == _expected(*_VECTOR_INDEX)
        vector_safe = (
            _statements(inside) == _expected(*_VECTOR_GUARDED)
            and not after
            and not _touches(before, "out", "a", "b")
        )
    gray_index = gray_safe = gray_rule = False
    gray_guard = _guarded(gray, "col < width && row < height")
    if gray_guard is not None:
        before, inside, after = gray_guard
        guarded = _statements(inside)
        loads = len(_GRAY_LOADS)
        gray_index = _statements(before) == _expected(*_GRAY_INDEX)
        gray_safe = (
            guarded[:loads] == _expected(*_GRAY_LOADS)
            and not after
            and not _touches(before, "gray", "rgb")
        )
        gray_rule = guarded[loads:] == _expected(_luma_statement(), _GRAY_STORE)
    vector_launch = _host_launch(vector_host, _VECTOR_LAUNCHER, (n,))
    gray_launch = _host_launch(gray_host, _GRAY_LAUNCHER, (width, height))
    checks = {
        "cdiv_definition": cdiv == _normalize("return (a + b - 1) / b;"),
        # _definitions found each signature exactly once.
        "vector_add_signature": True,
        "vector_add_index": vector_index,
        "vector_add_guard": vector_safe,
        "vector_add_grid": vector_launch == expected_vector,
        "rgb_to_grayscale_signature": True,
        "rgb_to_grayscale_index": gray_index,
        "rgb_to_grayscale_guard": gray_safe,
        "rgb_to_grayscale_rule": gray_rule,
        "rgb_to_grayscale_grid": gray_launch == expected_gray,
    }
    return CudaSourceCheck(
        checks=tuple((name, bool(checks[name])) for name in CHECK_NAMES),
        vector_add_launch=vector_launch,
        rgb_to_grayscale_launch=gray_launch,
    )


def require_cuda_source(text: str, **extents: object) -> CudaSourceCheck:
    """Return the check of ``text``, or raise naming every failed check."""

    result = check_cuda_source(text, **extents)
    if not result.passed:
        raise KernelLaunchError(
            "CUDA source fails structural checks: " + ", ".join(result.failures)
        )
    return result
