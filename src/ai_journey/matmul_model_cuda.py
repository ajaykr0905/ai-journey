"""Pinned CUDA C++ source for the naive matmul, and a compiler-free check of it.

``cuda_source`` writes the kernel and its host launcher from the launch math
of the simulator: one thread per element of C, ``row`` from y and ``col`` from
x, ``cdiv(extent, block)`` blocks on each axis and a guard on both axes. The
loop runs ``i`` from 0 to ``k - 1``. ``__fmul_rn`` and ``__fadd_rn`` round each
product and each sum to float32, ties to even, and CUDA never merges these
two intrinsics into a fused multiply-add, so the text keeps the roundings of
the reference. This lab never compiles or runs the text.

``check_cuda_source`` reads the text with the Day 73 checker's helpers. It
reads comments as a compiler does, fails every check on a line splice or a
trigraph, and accepts only the three definitions and no other code. Each
function must hold exactly its pinned statements. The checks cover the
signature, the row and col index expressions, the guard on both axes, the
loop bound, the accumulator, the store, ``cdiv`` and the host grid. The grid
check evaluates the ``dim3`` expressions for the given extents and requires
the simulator's launch configuration.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .kernel_launch_config import LaunchConfig
from .kernel_launch_cuda import (
    _CDIV,
    _DECIMAL,
    _braced,
    _code,
    _expected,
    _function_body,
    _guarded,
    _host_launch,
    _normalize,
    _statements,
    _touches,
)
from .matmul_model_kernels import X_COLUMNS, matmul_launch
from .matmul_model_reference import MatmulModelError, require_shape
from .memory_access_tiling import MatmulShape

CHECK_NAMES = (
    "cdiv_definition",
    "matmul_signature",
    "matmul_index",
    "matmul_guard",
    "matmul_loop",
    "matmul_accumulate",
    "matmul_store",
    "matmul_grid",
)
_KERNEL = (
    "__global__ void naive_matmul_kernel(const float* a, const float* b, "
    "float* c, int m, int n, int k)"
)
_HOST = (
    "void launch_naive_matmul(const float* a, const float* b, float* c, "
    "int m, int n, int k)"
)
_DEFINITIONS = (_CDIV, _KERNEL, _HOST)
_INDEX = (
    "int row = blockIdx.y * blockDim.y + threadIdx.y;",
    "int col = blockIdx.x * blockDim.x + threadIdx.x;",
)
_GUARD = "row < m && col < n"
_INIT = "float sum = 0.0f;"
_LOOP = "for (int i = 0; i < k; ++i)"
_ACCUMULATE = "sum = __fadd_rn(sum, __fmul_rn(a[row * k + i], b[i * n + col]));"
_STORE = "c[row * n + col] = sum;"
_FOR = re.compile(r"(?<![A-Za-z0-9_])for\(")
_LAUNCHER = re.compile(
    rf"dim3 block\({_DECIMAL},{_DECIMAL}\);"
    rf"dim3 grid\(cdiv\(n,{_DECIMAL}\),cdiv\(m,{_DECIMAL}\)\);"
    r"naive_matmul_kernel<<<grid,block>>>\(a,b,c,m,n,k\);"
)


def cuda_source(*, block: tuple[int, int]) -> str:
    """Return the pinned CUDA C++ text for one 2D block shape.

    The block is checked as a simulator block first, so the text never names
    a block that the Day 73 launch limits refuse.
    """

    matmul_launch(MatmulShape(1, 1, 1), block, X_COLUMNS)
    block_x, block_y = block
    return f"""\
// CUDA C++ source generated by ai_journey.matmul_model_cuda.
// The lab that generated this text did not compile or run it.
// It is source for a later run on an NVIDIA GPU.
// Launch math matches the simulator: one thread per element of C, row from
// y and col from x, cdiv(extent, block) blocks on each axis, and a guard on
// both axes. __fmul_rn and __fadd_rn round each product and each sum to
// float32 with ties to even, and CUDA never fuses them into one multiply-add.

{_CDIV} {{
    return (a + b - 1) / b;
}}

__global__ void naive_matmul_kernel(
    const float* a, const float* b, float* c, int m, int n, int k) {{
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    if (row < m && col < n) {{
        float sum = 0.0f;
        for (int i = 0; i < k; ++i) {{
            {_ACCUMULATE}
        }}
        c[row * n + col] = sum;
    }}
}}

void launch_naive_matmul(
    const float* a, const float* b, float* c, int m, int n, int k) {{
    dim3 block({block_x}, {block_y});
    dim3 grid(cdiv(n, {block_x}), cdiv(m, {block_y}));
    naive_matmul_kernel<<<grid, block>>>(a, b, c, m, n, k);
}}
"""


def _definitions(source: str) -> tuple[str, ...] | None:
    """Return the three function bodies if the text is those definitions only."""

    bodies = [_function_body(source, signature) for signature in _DEFINITIONS]
    if any(body is None for body in bodies):
        return None
    rebuilt = "".join(
        f"{_normalize(signature)}{{{body}}}"
        for signature, body in zip(_DEFINITIONS, bodies)
    )
    return tuple(bodies) if rebuilt == source else None


def _loop(code: str) -> tuple[str, str, str, str] | None:
    """Split code at its one ``for`` loop: before, header, body and after."""

    found = list(_FOR.finditer(code))
    if len(found) != 1:
        return None
    start = found[0].start()
    depth = 0
    for position in range(found[0].end() - 1, len(code)):
        if code[position] == "(":
            depth += 1
        elif code[position] == ")":
            depth -= 1
            if depth == 0:
                break
    else:
        return None
    opening = position + 1
    body = _braced(code, opening) if code[opening : opening + 1] == "{" else None
    if body is None:
        return None
    return code[:start], code[start:opening], body, code[opening + len(body) + 2 :]


@dataclass(frozen=True)
class MatmulCudaCheck:
    """What a compiler-free reading of the CUDA text confirmed, check by check."""

    checks: tuple[tuple[str, bool], ...]
    launch: LaunchConfig | None

    @property
    def passed(self) -> bool:
        return all(result for _, result in self.checks)

    @property
    def failures(self) -> tuple[str, ...]:
        return tuple(name for name, result in self.checks if not result)

    def to_mapping(self) -> dict[str, object]:
        return {
            "checks": dict(self.checks),
            "passed": self.passed,
            "launch": None if self.launch is None else self.launch.to_mapping(),
        }


def check_cuda_source(
    text: str, *, shape: MatmulShape, block: tuple[int, int]
) -> MatmulCudaCheck:
    """Check the text's structure and its grid for one shape and block.

    The kernel must be its two index statements, then one guard whose block
    holds the accumulator, the one loop and the store, and nothing after the
    guard. The grid check passes only if the host ``dim3`` expressions, with
    C unsigned division, give the configuration that the simulator launches.
    """

    if type(text) is not str:
        raise TypeError("CUDA source must be a string")
    checked = require_shape(shape)
    expected_launch = matmul_launch(checked, block, X_COLUMNS)
    code = _code(text)
    bodies = None if code is None else _definitions(_normalize(code))
    if bodies is None:
        return MatmulCudaCheck(
            checks=tuple((name, False) for name in CHECK_NAMES), launch=None
        )
    cdiv, kernel, host = bodies
    index = guard = loop = accumulate = store = False
    guarded = _guarded(kernel, _GUARD)
    if guarded is not None:
        before, inside, after = guarded
        index = _statements(before) == _expected(*_INDEX)
        guard = not after and not _touches(before, "a", "b", "c")
        split = _loop(inside)
        if split is not None:
            init, header, body, rest = split
            loop = header == _normalize(_LOOP)
            accumulate = _statements(init) == _expected(_INIT) and _statements(
                body
            ) == _expected(_ACCUMULATE)
            store = _statements(rest) == _expected(_STORE)
    launch = _host_launch(host, _LAUNCHER, (checked.n, checked.m))
    checks = {
        "cdiv_definition": cdiv == _normalize("return (a + b - 1) / b;"),
        # _definitions found each signature exactly once.
        "matmul_signature": True,
        "matmul_index": index,
        "matmul_guard": guard,
        "matmul_loop": loop,
        "matmul_accumulate": accumulate,
        "matmul_store": store,
        "matmul_grid": launch == expected_launch,
    }
    return MatmulCudaCheck(
        checks=tuple((name, bool(checks[name])) for name in CHECK_NAMES),
        launch=launch,
    )


def require_cuda_source(
    text: str, *, shape: MatmulShape, block: tuple[int, int]
) -> MatmulCudaCheck:
    """Return the check of ``text``, or raise naming every failed check."""

    result = check_cuda_source(text, shape=shape, block=block)
    if not result.passed:
        raise MatmulModelError(
            "CUDA source fails structural checks: " + ", ".join(result.failures)
        )
    return result
