"""Pinned CUDA C++ text of two Day 78 sum reductions, for a later NVIDIA run.

The Day 78 Metal lab adds float32 values in six steps, R0 to R5, on the
Apple GPU of this host. This module writes two of those steps as CUDA C++
text, each the twin of one Metal kernel:

* ``reduce_r1_shared`` follows ``reduce_r1_sequential``. Each thread loads
  one element into shared memory, or 0 at or past n. At stride s, the threads
  ``t < s`` add ``shared[t + s]``, and s halves from 128 to 1. A
  ``__syncthreads()`` follows the load and each level of the tree.
* ``reduce_warp_shuffle`` follows ``reduce_r3_simd_shuffle``. Each thread
  adds two elements 256 apart during the load. The tree stops at 32 values,
  and warp 0 adds them with ``__shfl_down_sync`` at offsets 16, 8, 4, 2 and 1,
  with no barrier. The mask ``0xffffffff`` names all 32 lanes, and all 32
  lanes of warp 0 take the branch, so every named lane calls each shuffle.

Each text also holds the combine kernel, the twin of ``reduce_combine``: one
block of 1024 threads adds the partial sums in a grid-stride loop with four
accumulators and then in a shared tree, so no kernel needs an atomic. The
host launcher sizes the grid, launches pass 1 and the combine in stream
order, and gives the combine the count of partials, ``grid.x``.

Each addition is ``__fadd_rn``. The CUDA Math API states that it rounds to
nearest even and that it never merges into a multiply-add. Thus the text
states each rounding and the order of the additions, which is the order of
its Metal twins. ``simd_shuffle_down`` is the Metal counterpart of
``__shfl_down_sync``, not the same instruction.

This lab never compiles, links or runs these texts, and this host has no
NVIDIA GPU, CUDA toolkit or ``nvcc``. Each text has a SHA-256 digest, so a
later run can show that it compiled the checked text.
"""

from __future__ import annotations

import re
import textwrap
from dataclasses import dataclass

from .gpu_reduce_plan import MAX_ELEMENTS, step_of
from .gpu_reduce_source import (
    COMBINE,
    COMBINE_ACCUMULATORS,
    COMBINE_GROUP_SIZE,
    KERNELS,
    LOADS_PER_THREAD,
    ONE_PER_THREAD,
    R1,
    R3,
    SEQUENTIAL_TREE,
    STEP_KERNELS,
    TREE_THEN_SHUFFLE,
    TWO_PER_THREAD,
    GpuReduceError,
)
from .gpu_tiled_cuda import FLOAT_BYTES, GpuTiledError
from .gpu_tiled_cuda import source_sha256 as _tiled_sha256
from .kernel_launch_config import WARP_SIZE, Dim3, LaunchConfig, ceil_div
from .kernel_launch_cuda import _CDIV
from .matmul_model_occupancy import ARCHITECTURE

FULL_MASK = 0xFFFFFFFF
SHUFFLE_OFFSETS = (16, 8, 4, 2, 1)
COMBINE_THREADS = COMBINE_GROUP_SIZE
COMBINE_SPAN = COMBINE_ACCUMULATORS * COMBINE_THREADS
COMBINE_LAUNCH = LaunchConfig(Dim3(1), Dim3(COMBINE_THREADS))
COMBINE_KERNEL = "reduce_combine_kernel"
MAX_STATIC_SHARED_BYTES = ARCHITECTURE.shared_memory_per_block_bytes
PASS_ONE_PARAMETERS = "(float* partials, const float* x, unsigned int n)"
COMBINE_SIGNATURE = (
    f"__global__ void {COMBINE_KERNEL}"
    "(float* out, const float* partials, unsigned int count)"
)
LAUNCHER_PARAMETERS = "(float* out, float* partials, const float* x, unsigned int n)"
# The load and the tree that the text of each Metal twin writes.
_TWINS = {
    R1: (ONE_PER_THREAD, SEQUENTIAL_TREE),
    R3: (TWO_PER_THREAD, TREE_THEN_SHUFFLE),
}
_NAME = re.compile(r"reduce_[a-z0-9_]{1,40}")
_HEADER = """\
// CUDA C++ source generated by ai_journey.gpu_reduce_cuda.
// The lab that generated this text did not compile or run it.
// It is source for a later run on an NVIDIA GPU.
"""


class GpuReduceCudaError(GpuReduceError):
    """Raised when a Day 78 CUDA reduction text, check or simulation is invalid."""


def require_n(n: object) -> int:
    """Return an input length that every unsigned index of the texts holds.

    With n at most 2^26, the largest index ``blockIdx.x * 512 + t + 256``
    stays far below 2^32, so no index wraps and each guard compares true
    values.
    """

    if type(n) is not int:
        raise TypeError("n must be an integer")
    if not 1 <= n <= MAX_ELEMENTS:
        raise GpuReduceCudaError(f"n must be between 1 and {MAX_ELEMENTS}")
    return n


def source_sha256(text: str) -> str:
    """Return the SHA-256 of an ASCII source text."""

    try:
        return _tiled_sha256(text)
    except GpuTiledError as error:
        raise GpuReduceCudaError(str(error)) from error


def tree_strides(threads: int, stop: int) -> tuple[int, ...]:
    """Return the strides of a sequential tree: threads / 2, halving, down to stop."""

    strides = []
    stride = threads // 2
    while stride >= stop:
        strides.append(stride)
        stride //= 2
    return tuple(strides)


@dataclass(frozen=True)
class CudaReduceKernel:
    """One pass-1 CUDA kernel, described by the Metal kernel that it follows.

    The load and the tree come from the twin's declared mapping and tree, so
    the CUDA text cannot drift from the Metal registry. Only twins whose
    order a text can state qualify: ``simd_sum`` states no order, and this
    lab writes no CUDA text of the interleaved tree of R0.
    """

    name: str
    metal_twin: str

    def __post_init__(self) -> None:
        if not isinstance(self.name, str) or _NAME.fullmatch(self.name) is None:
            raise GpuReduceCudaError("a kernel name must be reduce_ and a short slug")
        if self.metal_twin not in _TWINS:
            raise GpuReduceCudaError(
                "the Metal twin must be reduce_r1_sequential or reduce_r3_simd_shuffle"
            )
        twin = KERNELS[self.metal_twin]
        if (twin.mapping, twin.tree) != _TWINS[self.metal_twin]:
            raise GpuReduceCudaError(f"{self.metal_twin} changed its load or tree")

    @property
    def warp_shuffle(self) -> bool:
        return KERNELS[self.metal_twin].tree == TREE_THEN_SHUFFLE

    @property
    def prefix(self) -> str:
        """The prefix of this kernel's check names: r1 or shuffle."""

        return "shuffle" if self.warp_shuffle else "r1"

    @property
    def kernel_name(self) -> str:
        return f"{self.name}_kernel"

    @property
    def launcher_name(self) -> str:
        return f"launch_{self.name}"

    @property
    def file_name(self) -> str:
        return f"{self.name}.cu"

    @property
    def same_order_as(self) -> tuple[str, ...]:
        """The Metal kernels that add the same pairs in the same order.

        These are the twin and the earlier kernel whose order the plan says
        that the twin keeps: R3 keeps the order of R2.
        """

        earlier = step_of(self.metal_twin).same_order_as
        names = {self.metal_twin} | ({earlier} if earlier else set())
        return tuple(name for name in STEP_KERNELS if name in names)

    @property
    def block_threads(self) -> int:
        return KERNELS[self.metal_twin].group_size

    @property
    def elements_per_thread(self) -> int:
        return LOADS_PER_THREAD if self.warp_shuffle else 1

    @property
    def elements_per_block(self) -> int:
        return self.block_threads * self.elements_per_thread

    @property
    def shared_memory_bytes(self) -> int:
        """One float of shared memory for each thread of the block."""

        return self.block_threads * FLOAT_BYTES

    @property
    def tree_stop(self) -> int:
        """The values left in shared memory after the tree: 1, or one warp."""

        return WARP_SIZE if self.warp_shuffle else 1

    @property
    def tree_strides(self) -> tuple[int, ...]:
        return tree_strides(self.block_threads, self.tree_stop)

    @property
    def shuffle_offsets(self) -> tuple[int, ...]:
        return SHUFFLE_OFFSETS if self.warp_shuffle else ()

    @property
    def barriers_per_block(self) -> int:
        """Barriers that each thread reaches: one after the load, one per level."""

        return 1 + len(self.tree_strides)

    def launch(self, n: int) -> LaunchConfig:
        """Return the pass-1 launch: the fewest blocks whose elements cover n."""

        count = require_n(n)
        return LaunchConfig(
            Dim3(ceil_div(count, self.elements_per_block)), Dim3(self.block_threads)
        )

    def partial_count(self, n: int) -> int:
        """Return the partial sums of pass 1: one for each block."""

        return self.launch(n).grid.x

    def to_mapping(self) -> dict[str, object]:
        return {
            "name": self.name,
            "metal_twin": self.metal_twin,
            "same_order_as": list(self.same_order_as),
            "block_threads": self.block_threads,
            "elements_per_thread": self.elements_per_thread,
            "shared_memory_bytes": self.shared_memory_bytes,
            "tree_strides": list(self.tree_strides),
            "shuffle_offsets": list(self.shuffle_offsets),
            "full_mask": f"0x{FULL_MASK:08x}" if self.warp_shuffle else None,
            "barriers_per_block": self.barriers_per_block,
        }


R1_SHARED = CudaReduceKernel(name="reduce_r1_shared", metal_twin=R1)
WARP_SHUFFLE = CudaReduceKernel(name="reduce_warp_shuffle", metal_twin=R3)
PINNED_KERNELS = (R1_SHARED, WARP_SHUFFLE)
COMBINE_STRIDES = tree_strides(COMBINE_THREADS, 1)
COMBINE_BARRIERS = 1 + len(COMBINE_STRIDES)
COMBINE_SHARED_BYTES = COMBINE_THREADS * FLOAT_BYTES


def require_kernel(kernel: object) -> CudaReduceKernel:
    """Return one of the two pinned kernels; any other value is refused."""

    if type(kernel) is not CudaReduceKernel:
        raise TypeError("kernel must be CudaReduceKernel")
    if kernel not in PINNED_KERNELS:
        raise GpuReduceCudaError(f"{kernel.name} is not a pinned CUDA kernel")
    return kernel


def pass_one_signature(kernel: CudaReduceKernel) -> str:
    return f"__global__ void {require_kernel(kernel).kernel_name}{PASS_ONE_PARAMETERS}"


def launcher_signature(kernel: CudaReduceKernel) -> str:
    return f"void {require_kernel(kernel).launcher_name}{LAUNCHER_PARAMETERS}"


def _comment(*sentences: str) -> str:
    """Wrap sentences into ``//`` lines of at most 78 characters."""

    lines = textwrap.wrap(
        " ".join(sentences), width=75, break_long_words=False, break_on_hyphens=False
    )
    return "\n".join(f"// {line}" for line in lines)


def _tree(stop: str) -> str:
    """Return a sequential tree loop: one barrier at the end of each level."""

    return f"""\
    for (unsigned int s = blockDim.x / 2u; s {stop}; s >>= 1u) {{
        if (t < s) {{
            shared[t] = __fadd_rn(shared[t], shared[t + s]);
        }}
        __syncthreads();
    }}"""


def combine_source() -> str:
    """Return the pinned text of the combine kernel that both files hold."""

    stride = COMBINE_THREADS
    comment = _comment(
        f"Pass 2: one block of {stride} threads. Thread t adds the partials t,",
        f"t + {stride}, t + {2 * stride} and so on in {COMBINE_ACCUMULATORS}",
        f"accumulators. Then the block adds the {stride} thread sums with",
        "sequential addressing, and thread 0 writes out[0]. The grid-stride loop",
        f"reads each partial once, because the launch has exactly {stride} threads.",
    )
    loads = "\n".join(
        f"        a{index} = __fadd_rn(a{index}, partials[e"
        + (f" + {index * stride}u" if index else "")
        + "]);"
        for index in range(COMBINE_ACCUMULATORS)
    )
    return f"""\
{comment}
__global__ void {COMBINE_KERNEL}(
    float* out, const float* partials, unsigned int count) {{
    __shared__ float shared[{stride}];
    unsigned int t = threadIdx.x;
    float a0 = 0.0f, a1 = 0.0f, a2 = 0.0f, a3 = 0.0f;
    unsigned int e = t;
    for (; e + {3 * stride}u < count; e += {COMBINE_SPAN}u) {{
{loads}
    }}
    for (; e < count; e += {stride}u) {{
        a0 = __fadd_rn(a0, partials[e]);
    }}
    shared[t] = __fadd_rn(__fadd_rn(a0, a1), __fadd_rn(a2, a3));
    __syncthreads();
{_tree("> 0u")}
    if (t == 0u) {{
        out[0] = shared[0];
    }}
}}
"""


def _r1_kernel(kernel: CudaReduceKernel) -> str:
    threads = kernel.block_threads
    comment = _comment(
        "R1 with shared memory: each thread loads one element, or 0 at or past n.",
        "At stride s, the threads t < s add shared[t + s], and s halves from",
        f"{threads // 2} to 1. A barrier follows the load and each level, and no",
        "barrier is inside a guard. Thread 0 writes the partial sum of its block.",
        f"Each addition is __fadd_rn, in the order of the Metal kernel {R1}.",
    )
    return f"""\
{comment}
__global__ void {kernel.kernel_name}(
    float* partials, const float* x, unsigned int n) {{
    __shared__ float shared[{threads}];
    unsigned int t = threadIdx.x;
    unsigned int i = blockIdx.x * {kernel.elements_per_block}u + t;
    shared[t] = i < n ? x[i] : 0.0f;
    __syncthreads();
{_tree("> 0u")}
    if (t == 0u) {{
        partials[blockIdx.x] = shared[0];
    }}
}}
"""


def _shuffle_kernel(kernel: CudaReduceKernel) -> str:
    threads = kernel.block_threads
    *strides, last = kernel.tree_strides
    *offsets, final = SHUFFLE_OFFSETS
    comment = _comment(
        f"Warp shuffles: each thread adds two elements {threads} apart, or 0 at",
        "or past n. The tree in shared memory adds pairs at strides",
        f"{', '.join(map(str, strides))} and {last}, with a barrier after each",
        f"level. Then warp 0 adds the last {WARP_SIZE} values with",
        f"__shfl_down_sync at offsets {', '.join(map(str, offsets))} and {final},",
        f"with no barrier. The mask 0x{FULL_MASK:08x} names all {WARP_SIZE} lanes,",
        f"and all {WARP_SIZE} lanes of warp 0 call each shuffle. Lane 0 writes the",
        "partial sum of its block. Each addition is __fadd_rn, in the order of",
        f"the Metal kernels {' and '.join(kernel.same_order_as)}.",
    )
    shuffles = "\n".join(
        "        w = __fadd_rn(w, "
        f"__shfl_down_sync(0x{FULL_MASK:08x}u, w, {offset}u));"
        for offset in SHUFFLE_OFFSETS
    )
    second = f"i + {threads}u < n ? x[i + {threads}u] : 0.0f"
    return f"""\
{comment}
__global__ void {kernel.kernel_name}(
    float* partials, const float* x, unsigned int n) {{
    __shared__ float shared[{threads}];
    unsigned int t = threadIdx.x;
    unsigned int lane = t % {WARP_SIZE}u;
    unsigned int warp = t / {WARP_SIZE}u;
    unsigned int i = blockIdx.x * {kernel.elements_per_block}u + t;
    float v = __fadd_rn(i < n ? x[i] : 0.0f, {second});
    shared[t] = v;
    __syncthreads();
{_tree(f">= {WARP_SIZE}u")}
    if (warp == 0u) {{
        float w = shared[lane];
{shuffles}
        if (lane == 0u) {{
            partials[blockIdx.x] = w;
        }}
    }}
}}
"""


def cuda_source(kernel: CudaReduceKernel) -> str:
    """Return the pinned text of one file: cdiv, pass 1, the combine, the launcher.

    Each file defines its own ``cdiv`` and combine kernel, so a later run
    compiles each file alone as one translation unit.
    """

    checked = require_kernel(kernel)
    pass_one = _shuffle_kernel(checked) if checked.warp_shuffle else _r1_kernel(checked)
    combine = COMBINE_LAUNCH
    passes = _comment(
        f"Pass 1 writes one partial sum for each block of {checked.block_threads}",
        "threads, and the combine kernel adds the partials. The launcher runs",
        "both kernels on one stream, so the combine reads each partial after",
        "pass 1 wrote it.",
    )
    return f"""\
{_HEADER}\
{passes}

{_CDIV} {{
    return (a + b - 1) / b;
}}

{pass_one}
{combine_source()}
void {checked.launcher_name}(
    float* out, float* partials, const float* x, unsigned int n) {{
    dim3 block({checked.block_threads});
    dim3 grid(cdiv(n, {checked.elements_per_block}));
    {checked.kernel_name}<<<grid, block>>>(partials, x, n);
    {COMBINE_KERNEL}<<<{combine.grid.x}, {combine.block.x}>>>(out, partials, grid.x);
}}
"""


def source_files() -> tuple[tuple[str, str], ...]:
    """Return the file name and the text of each pinned source, R1 first."""

    return tuple((kernel.file_name, cuda_source(kernel)) for kernel in PINNED_KERNELS)


def combine_mapping() -> dict[str, object]:
    """Return what both texts declare about the combine kernel and its launch."""

    return {
        "name": COMBINE_KERNEL,
        "metal_twin": COMBINE,
        "launch": COMBINE_LAUNCH.to_mapping(),
        "accumulators": COMBINE_ACCUMULATORS,
        "stride": COMBINE_THREADS,
        "span": COMBINE_SPAN,
        "shared_memory_bytes": COMBINE_SHARED_BYTES,
        "tree_strides": list(COMBINE_STRIDES),
        "barriers_per_block": COMBINE_BARRIERS,
        "source_sha256": source_sha256(combine_source()),
    }
