"""Tests of the PTX reader on small synthetic texts and on the committed PTX.

The committed PTX is the triton 3.9.0 output for ``sm_80`` and the config
``m32_n64_k32_g8_w2_s5``. Its counts are pinned here so that a change of the
reader or of the fixture shows in a test. No test imports triton.
"""

from pathlib import Path

import pytest

from ai_journey.triton_ir_manifest import TritonIrError
from ai_journey.triton_ir_ptx import FAMILIES, family, read_ptx

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "day80_triton_ir"
PTX = FIXTURES / "sm_80" / "m32_n64_k32_g8_w2_s5" / "ptx.ptx"
SOURCE = "<ai_journey.triton_matmul_kernel.TRITON_SOURCE sha256=abc>"

SMALL = f"""//
// Generated by hand
//

.version 8.8
.target sm_80
.address_size 64

.extern .shared .align 16 .b8 global_smem[];
.shared .align 4 .b32 table[8];
.visible .entry tiny(
\t.param .u64 .ptr .global .align 1 tiny_param_0,
\t.param .u32 tiny_param_1
)
.reqntid 32
{{
\t.reg .pred \t%p<3>;
\t.reg .b32 \t%r<9>;
\t.loc\t1 5 0
\tld.param.b32 \t%r1, [tiny_param_1];
$L__BB0_1:                              // =>This Inner Loop Header: Depth=1
\t.loc\t2 43 13, function_name $L__info_string0, inlined_at 1 7 17 // helper
\tsetp.lt.s32 \t%p1, %r1, 4;
\t.loc\t1 8 3
\t// begin inline asm
\t@%p1 cp.async.ca.shared.global [ %r2 + 0 ], [ %rd1 + 0 ], 0x4, %r3;
\t// end inline asm
\tcp.async.commit_group;
\tcp.async.wait_group \t0;
\tbar.sync \t0;
\tld.shared.v4.b32 \t{{%r4, %r5, %r6, %r7}}, [%r2];
\tfma.rn.f32 \t%r8, %r4, %r5, %r8;
\t@!%p1 bra \t$L__BB0_1;
\t.loc\t1 0 0
\tmma.sync.aligned.m16n8k8.row.col.f32.tf32.tf32.f32 {{%r1}}, {{%r2}}, {{%r3}}, {{%r4}};
\tld.global.b32 \t%r1, [%rd1];
\t.loc\t1 9 3
\t@%p2 st.global.b32 [ %rd1 + 0 ], {{ %r8 }};
\tret;
$L__func_end0:
}}
\t.file\t1 "{SOURCE}"
\t.file\t2 "/site-packages/triton/language/standard.py"
"""


def small():
    return read_ptx(SMALL)


def test_the_header_entry_and_declarations_of_a_small_text():
    summary = small()
    assert (summary.version, summary.target, summary.address_size) == (
        "8.8",
        "sm_80",
        64,
    )
    assert summary.entry == "tiny"
    assert summary.parameters == (
        (".u64 .ptr .global .align 1", "tiny_param_0"),
        (".u32", "tiny_param_1"),
    )
    assert summary.reqntid == "32"
    assert summary.registers == (("pred", "p", 3), ("b32", "r", 9))
    assert summary.to_mapping()["shared"] == [
        {
            "name": "global_smem",
            "extern": True,
            "align": 16,
            "element": "b8",
            "elements": None,
        },
        {"name": "table", "extern": False, "align": 4, "element": "b32", "elements": 8},
    ]
    assert summary.source_file == 1


def test_the_families_and_the_loop_of_a_small_text():
    summary = small()
    families = summary.families
    assert tuple(families) == FAMILIES
    assert {name: count for name, count in families.items() if count} == {
        "ld.global": 1,
        "st.global": 1,
        "cp.async": 1,
        "cp.async.commit_group": 1,
        "cp.async.wait_group": 1,
        "ld.shared": 1,
        "bar.sync": 1,
        "fma.rn.f32": 1,
        "mma": 1,
        "setp": 1,
        "branch": 1,
        "other": 2,
    }
    mapping = summary.to_mapping()
    assert mapping["predicated"] == 3
    assert mapping["instructions"] == 13
    (loop,) = mapping["loops"]
    assert (loop["label"], loop["instructions"]) == ("$L__BB0_1", 8)
    assert loop["families"]["fma.rn.f32"] == 1
    assert loop["families"]["ld.global"] == 0


def test_each_instruction_gets_its_source_line_and_an_inlined_call_its_call():
    lines = {item.opcode: item.source_line for item in small().instructions}
    assert lines["ld.param.b32"] == 5
    assert lines["setp.lt.s32"] == 7
    assert lines["cp.async.ca.shared.global"] == 8
    assert lines["mma.sync.aligned.m16n8k8.row.col.f32.tf32.tf32.f32"] is None
    assert lines["st.global.b32"] == 9
    guards = [item.guard for item in small().instructions if item.guard]
    assert guards == ["%p1", "!%p1", "%p2"]


@pytest.mark.parametrize(
    ("opcode", "name"),
    [
        ("ld.global.v4.b32", "ld.global"),
        ("st.global.b32", "st.global"),
        ("cp.async.cg.shared.global", "cp.async"),
        ("cp.async.commit_group", "cp.async.commit_group"),
        ("cp.async.wait_all", "cp.async.wait_group"),
        ("ld.shared.b32", "ld.shared"),
        ("st.shared.v2.b32", "st.shared"),
        ("ldmatrix.sync.aligned.m8n8.x4.shared.b16", "ldmatrix"),
        ("barrier.sync", "bar.sync"),
        ("fma.rn.f32", "fma.rn.f32"),
        ("fma.rn.f64", "other"),
        ("wgmma.mma_async.sync.aligned", "mma"),
        ("setp.gt.s32", "setp"),
        ("selp.b32", "selp"),
        ("bra.uni", "branch"),
        ("ld.param.b32", "other"),
    ],
)
def test_each_opcode_family(opcode, name):
    assert family(opcode) == name


@pytest.mark.parametrize(
    ("edit", "message"),
    [
        (lambda t: t.replace(".target sm_80\n", ""), "must declare .target"),
        (
            lambda t: t.replace(".version 8.8\n", ".version 8.8\n.version 8.8\n"),
            "twice",
        ),
        (lambda t: t.replace(".visible .entry tiny(", ".func tiny("), "exactly one"),
        (lambda t: t + ".visible .entry other(\n)\n{\n}\n", "exactly one"),
        (
            lambda t: t.replace("\t.param .u32 tiny_param_1\n)", "\t.param .u32 x,"),
            "parameter",
        ),
        (lambda t: t.replace("\n{\n", "\n"), "no body"),
        (lambda t: t.replace("\n}\n", "\n"), "never closes"),
        (lambda t: t.replace("\tret;", "\tret"), "not an instruction"),
        (lambda t: t + "\u00b5", "ASCII"),
    ],
)
def test_a_text_that_is_not_one_ptx_entry_is_refused(edit, message):
    with pytest.raises(TritonIrError, match=message):
        read_ptx(edit(SMALL))


def committed():
    return read_ptx(PTX.read_text(encoding="ascii"))


def test_the_committed_ptx_header_and_declarations():
    summary = committed()
    mapping = summary.to_mapping()
    assert (summary.version, summary.target, summary.address_size) == (
        "8.8",
        "sm_80",
        64,
    )
    assert summary.entry == "matmul_kernel"
    # 3 matrix pointers, 9 int32 arguments, then 2 pointers that Triton adds.
    types = [kind for kind, _ in summary.parameters]
    pointer = ".u64 .ptr .global .align 1"
    assert types == [pointer] * 3 + [".u32"] * 9 + [pointer] * 2
    # 2 warps of 32 threads.
    assert summary.reqntid == "64"
    assert summary.registers == (
        ("pred", "p", 251),
        ("b32", "r", 2296),
        ("b64", "rd", 480),
    )
    assert mapping["shared"] == [
        {
            "name": "global_smem",
            "extern": True,
            "align": 16,
            "element": "b8",
            "elements": None,
        }
    ]
    assert mapping["instructions"] == 3097
    assert mapping["predicated"] == 34


def test_the_committed_ptx_instruction_families():
    assert committed().families == {
        "ld.global": 0,
        "st.global": 32,
        "cp.async": 240,
        "cp.async.commit_group": 10,
        "cp.async.wait_group": 2,
        "ld.shared": 96,
        "ldmatrix": 8,
        "st.shared": 8,
        "bar.sync": 18,
        "fma.rn.f32": 1024,
        "mma": 0,
        "setp": 218,
        "selp": 377,
        "branch": 3,
        "other": 1061,
    }
    opcodes = committed().opcodes
    assert opcodes["cp.async.ca.shared.global"] == 240
    assert opcodes["ld.shared.v4.b32"] == 96
    assert opcodes["ldmatrix.sync.aligned.m8n8.x4.shared.b16"] == 8
    assert (
        sum(count for name, count in opcodes.items() if name.startswith("cp.async"))
        == 252
    )
    assert not [name for name in opcodes if "mma" in name]


def test_the_committed_ptx_has_one_k_loop_with_one_tile_of_fma():
    (loop,) = committed().to_mapping()["loops"]
    assert (loop["label"], loop["first_line"], loop["last_line"]) == (
        "$L__BB0_3",
        2216,
        3869,
    )
    assert loop["instructions"] == 1450
    nonzero = {name: count for name, count in loop["families"].items() if count}
    # 32 x 64 x 32 multiply-adds over 64 threads: 1024 for each thread.
    assert nonzero == {
        "cp.async": 48,
        "cp.async.commit_group": 2,
        "cp.async.wait_group": 1,
        "ld.shared": 96,
        "bar.sync": 2,
        "fma.rn.f32": 1024,
        "setp": 37,
        "selp": 131,
        "branch": 1,
        "other": 108,
    }
